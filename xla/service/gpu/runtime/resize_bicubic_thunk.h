// This class stores everything that StreamExecutor needs to launch a CUDA
// ResizeBicubic. It is generated by IrEmitter.
class ResizeBicubicFwdThunk : public Thunk {
 public:
  // Constructs a thunk for launching a CUDA FlashAttention.
  ResizeBicubicFwdThunk(
      ThunkInfo thunk_info, ResizeBicubicFwdConfig config,
      BufferAllocation::Slice input,
      BufferAllocation::Slice output);

  ResizeBicubicFwdThunk(const ResizeBicubicFwdThunk &) = delete;
  ResizeBicubicFwdThunk &operator=(const ResizeBicubicFwdThunk &) = delete;

  absl::Status ExecuteOnStream(const ExecuteParams &params) override;

 private:
  ResizeBicubicFwdConfig config_;
  BufferAllocation::Slice input_;
  BufferAllocation::Slice output_;
};

